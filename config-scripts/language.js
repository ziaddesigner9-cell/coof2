// تنسيق الأسعار مع رمز العملة المناسب (مع إبقاء القيمة العددية ثابتة)
function formatPrice(amount) {
    let lang = 'ar';
    try {
        lang = localStorage.getItem('coof2_userLang') || 'ar';
    } catch (_) {}

    const num = parseFloat(amount || 0).toFixed(2);
    if (lang === 'ar') {
        return num + ' ر.س';
    } else if (lang === 'en' || lang === 'en-AU') {
        return '$' + num;
    } else if (lang === 'de' || lang === 'fr') {
        return num + ' €';
    }
    return num + ' SAR';
}

// تطبيق اللغة والاتجاهات
function applyLanguage(lang) {
    document.documentElement.setAttribute('dir', (lang === 'ar') ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);
    try {
        localStorage.setItem('coof2_userLang', lang); // حفظ اللغة
    } catch (err) {
        console.error("فشل حفظ اللغة في localStorage:", err);
    }

    // ترجمة الحقول ذات السمة data-key
    document.querySelectorAll('[data-key]').forEach(function(el) {
        var key = el.getAttribute('data-key');
        if (translations[lang] && translations[lang][key]) {
            // التحقق من الحقول التي تحتوي على إدخال placeholder
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.setAttribute('placeholder', translations[lang][key]);
            } else {
                el.innerText = translations[lang][key];
            }
        }
    });

    // تحديث صيغ رقم الهاتف في السلة
    var phoneInput = document.getElementById('deliveryPhone');
    if (phoneInput && phoneConfig[lang]) {
        phoneInput.setAttribute('placeholder', phoneConfig[lang].placeholder);
    }

    // إطلاق حدث للمستمعين الآخرين لتحديث نصوصهم البرمجية
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: lang } }));
}

// تغيير اللغة مباشرة لرمز لغة معين
function changeLanguageTo(lang) {
    applyLanguage(lang);
}

// تبديل ثنائي احتياطي
function changeLanguage() {
    let currentLang = 'ar';
    try {
        currentLang = localStorage.getItem('coof2_userLang') || 'ar';
    } catch (_) {}
    const newLang = (currentLang === 'ar') ? 'en' : 'ar';
    applyLanguage(newLang);
}

